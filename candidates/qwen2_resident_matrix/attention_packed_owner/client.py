"""Explicit profile-2 client for the original serialized MatrixService.

This is a software handshake model. A nonfinal accepted step returns metadata
only. A final output is a reference to the service's own immutable MatrixResult;
it is never copied or retired by result_fire. The consumer explicitly ACKs the
canonical tag after every registered bank write has received its matching ACK.
There are no parent/bank ticks, arithmetic arrays, or native-library loads here.
"""
from dataclasses import dataclass, replace

from ..ffn_public.prefix_arithmetic import ArithmeticFault
from ..ffn_attention.matrix_service import (
    MatrixProtocolError, NormalGroup, NormalStep, require,
)


def _uint(value, bits):
    return type(value) is int and 0 <= value < 1 << bits


@dataclass(frozen=True)
class PackedTag:
    owner_tag: int
    group: int
    ticket: int
    epoch: int

    def __post_init__(self):
        require(_uint(self.owner_tag, 32) and _uint(self.group, 32)
                and self.group > 0 and _uint(self.ticket, 64)
                and _uint(self.epoch, 64), 'noncanonical packed Matrix tag')


@dataclass(frozen=True)
class PackedRequest:
    opcode: int
    a: tuple
    b: tuple
    clear: bool
    last: bool
    steps: int
    slice_mask: int = 1
    selected: tuple = ()


@dataclass(frozen=True)
class PackedStepAccepted:
    """Accepted nonfinal arithmetic step, with no fabricated result payload."""
    tag: PackedTag
    index: int
    error: bool = False
    value: object = None


@dataclass(frozen=True)
class PackedResult:
    tag: PackedTag
    service_result: object
    selected: tuple

    @property
    def value(self):
        return self.service_result.value

    @property
    def error(self):
        return self.service_result.error

    @property
    def ticket(self):
        return self.tag.ticket

    @property
    def epoch(self):
        return self.tag.epoch

    def selected_words(self):
        """Read selected cells only; unconsumed NaN/Inf is not a protocol error."""
        self.check_selected()
        return tuple(self.value[row][column] for row,column in self.selected)

    def check_selected(self):
        # Scan the live FIFO view without allocating a selected-output tile.
        if any((self.value[row][column] & 0x7f800000) == 0x7f800000 for row,column in self.selected):
            raise ArithmeticFault('nonfinite selected packed Matrix cell')


@dataclass(frozen=True)
class PackedConsumerAck:
    tag: PackedTag

    def __post_init__(self):
        require(type(self.tag) is PackedTag, 'noncanonical packed consumer ACK')


@dataclass(frozen=True)
class PackedRetired:
    """The consumer ACK completed both actual service result and done edges."""
    tag: PackedTag
    error: bool = False
    value: object = None


@dataclass(frozen=True)
class PackedWriteTag:
    result: PackedTag
    bank: str
    address: int
    generation: int
    serial: int

    def __post_init__(self):
        require(type(self.result) is PackedTag and type(self.bank) is str
                and bool(self.bank) and len(self.bank) <= 64
                and _uint(self.address, 64) and _uint(self.generation, 64)
                and _uint(self.serial, 64), 'noncanonical packed write tag')


@dataclass(frozen=True)
class PackedWriteAck:
    tag: PackedWriteTag
    error: bool = False

    def __post_init__(self):
        require(type(self.tag) is PackedWriteTag and type(self.error) is bool,
                'noncanonical packed write ACK')


class PackedClient:
    """One active group, one service-held final result, bounded write metadata.

    tick returns PRE-edge ports. result_fire on PackedResult is delivery only;
    service_result_fire is the later explicit retirement. A PackedConsumerAck is
    an ordinary request, followed by a PackedRetired response after MatrixDone.
    In abort/drain, result_ready authorizes a matching cancellation ACK for this
    client's held result, after pending writes drain. Existing visible payload
    objects stay unchanged. No success response is generated by that path.
    """
    MAX_WRITE_DEBTS = 64

    def __init__(self, service, owner):
        service._check_owner(owner, 'normal')
        self.service, self.owner, self.epoch = service, owner, service.epoch
        self.owner_tag = service.owner_tag
        self.acquisition = service.counts.get('owner_acquires', 0)
        self.resource_address = service.resource_address
        # Generated profile-2 service modules own their own exact dataclass
        # types. Use those types without replacing/subclassing MatrixService.
        self._group_type = service.accept_group.__func__.__globals__.get('NormalGroup', NormalGroup)
        self._step_type = service.accept_step.__func__.__globals__.get('NormalStep', NormalStep)
        self.state, self.active, self.poison = 'idle', False, False
        self.aborting = False
        self.group_serial = self.index = 0
        self.group = self.request = self.response = self.tag = None
        self._held = None
        self._exposed = self._delivered = False
        self._write_debts = set()
        self._last_write_serial = -1

    @property
    def write_debts(self):
        return len(self._write_debts)

    @property
    def held_tag(self):
        return self.tag if self._held is not None else None

    @property
    def drained(self):
        return (not self.active and self.request is None and self.response is None
                and self._held is None and not self._write_debts
                and not (self.service.lib.matrix_state() & (4 | 8 | 32 | 64)))

    def ports(self):
        ready = (not self.poison and not self.service.reset_required
                 and self.epoch == self.service.epoch)
        return dict(request_ready=ready and (self.state == 'idle' or
                    (self.state == 'held' and not self._write_debts)),
                    result=self.response if self.state.startswith('reply_') else None,
                    reset_required=self.poison or self.service.reset_required,
                    drained=self.drained, write_debts=len(self._write_debts),
                    held_tag=self.held_tag)

    def _check(self):
        self.service._check_owner(self.owner, 'normal')
        self.service._check_event(epoch=self.epoch)
        require(self.service.resource_address == self.resource_address and
                self.service.owner_tag == self.owner_tag and
                self.service.counts.get('owner_acquires', 0) == self.acquisition,
                'packed Matrix resource/acquisition changed')

    def _matching(self, tag):
        require(type(tag) is PackedTag and self.tag is not None and tag == self.tag,
                'stale or foreign packed Matrix ACK')
        self.service._check_event(ticket=tag.ticket, epoch=tag.epoch)

    def register_write(self, tag):
        """Register an actually accepted write; stores tags, never payload."""
        self._check()
        require(type(tag) is PackedWriteTag, 'noncanonical packed write tag')
        self._matching(tag.result)
        require(self.state == 'held' and self._delivered and not self.aborting,
                'packed write outside held consumer result')
        require(len(self._write_debts) < self.MAX_WRITE_DEBTS and
                tag.serial > self._last_write_serial,
                'packed write debt capacity or duplicate/stale serial')
        self._write_debts.add(tag)
        self._last_write_serial = tag.serial
        self.service.counts['packed_write_debts'] += 1

    def commit_write(self, ack):
        """Discharge only the exact accepted debt; return publication eligibility."""
        self._check()
        require(type(ack) is PackedWriteAck, 'noncanonical packed write ACK')
        self._matching(ack.tag.result)
        require(ack.tag in self._write_debts, 'foreign or repeated packed write ACK')
        self._write_debts.remove(ack.tag)
        self.service.counts['packed_write_acks'] += 1
        if ack.error:
            self._abort()
        return not (ack.error or self.aborting or self.poison)

    def _abort(self):
        if not self.aborting:
            self.service.abort(self.owner)
        self.poison = self.aborting = True

    def _validate_request(self, request):
        require(type(request) is PackedRequest and type(request.clear) is bool
                and type(request.last) is bool,
                'packed request type/flags')
        require(_uint(request.opcode, 32) and _uint(request.steps, 32)
                and _uint(request.slice_mask, 32)
                and ((request.opcode, request.steps, request.slice_mask) == (0x23, 8, 255)
                or (request.opcode == 0x24 and 1 <= request.steps <= 128
                    and request.slice_mask == 15)), 'packed profile-2 shape')
        require(len(request.a) == 16 and len(request.b) == 256 and
                all(_uint(word, 16) for word in (*request.a, *request.b)),
                'packed BF16 packet widths')
        require(type(request.selected) is tuple and len(request.selected) <= 4096
                and all(type(cell) is tuple and len(cell) == 2
                    and _uint(cell[0], 4) and _uint(cell[1], 8)
                    and (request.opcode == 0x23 or cell[1] < 128)
                    for cell in request.selected), 'packed selected coordinates')
        require(not request.selected or request.last, 'selection on nonfinal packed step')
        require(bool(request.clear) != self.active, 'packed clear/group ownership mismatch')
        index = 0 if request.clear else self.index
        require(request.last == (index + 1 == request.steps), 'packed last/index mismatch')
        if self.active:
            require((request.opcode, request.steps, request.slice_mask) ==
                    (self.group.opcode, self.group.steps, self.group.slice_mask),
                    'packed shape changed within group')

    def _retire_result(self, p):
        require(self._held is self.service.result and self._held is not None,
                'packed result no longer held by MatrixService')
        self._matching(self.tag)
        self.service.retire_result(self.owner, self._held)
        self._held = None
        p['service_result_fire'] = True

    def _retire_done(self, p, done_override):
        actual = self.service.done
        if actual is None:
            return False
        done = actual if done_override is None else done_override
        require(type(done) is type(actual) and _uint(done.tag, 32)
                and _uint(done.ticket, 64) and _uint(done.epoch, 64)
                and type(done.error) is bool and
                (done.tag, done.ticket, done.epoch, done.error) ==
                (actual.tag, actual.ticket, actual.epoch, actual.error),
                'stale or foreign packed MatrixDone')
        require(self.tag is not None and done.tag == self.tag.group
                and done.ticket == self.tag.ticket and done.epoch == self.tag.epoch,
                'packed MatrixDone group mismatch')
        self.service.retire_done(self.owner, done)
        self.active = False
        self.poison |= done.error
        p['service_done_fire'] = True
        return True

    def _abort_edge(self, p, result_ready, service_result_ready, service_done_ready, done_override):
        # Visible responses are immutable and held through owner backpressure.
        if p['result'] is not None and result_ready:
            p['result_fire'] = True
            self.response = None
            self._delivered = True
        if self.service.result is not None:
            self._held = self.service.result
            can_cancel = not self._exposed or (result_ready and self.response is None)
            if can_cancel and not self._write_debts and service_result_ready:
                self._retire_result(p)
                self.service.counts['packed_cancel_acks'] += 1
        # Do not consume a done which appeared only because of this edge's
        # result retirement; all outputs obey pre-edge ready/valid semantics.
        if (not p['service_result_fire'] and self.service.result is None
                and service_done_ready and self.service.done is not None):
            self._retire_done(p, done_override)
        if (self.service.result is None and self.service.done is None
                and not (self.service.lib.matrix_state() & (4 | 8))
                and self.response is None and not self._write_debts):
            self.active = False
            self.request = self.group = self._held = None
            self.state = 'locked'
        return p

    def tick(self, *, request=None, result_ready=False, service_result_ready=True,
             service_done_ready=True, abort=False, done_override=None):
        self._check()
        require(all(type(flag) is bool for flag in (result_ready, service_result_ready,
                service_done_ready, abort)), 'packed readiness flags must be bool')
        p = self.ports()
        p.update(request_fire=False, result_fire=False, service_result_fire=False,
                 service_done_fire=False)
        self.service.counts['packed_model_ticks'] += 1
        if abort:
            self._abort()
        if self.service.reset_required:
            self.poison = self.aborting = True
        if self.aborting:
            return self._abort_edge(p, result_ready, service_result_ready,
                                    service_done_ready, done_override)
        if type(request) is PackedConsumerAck:
            self._matching(request.tag)  # Reject stale/foreign ACK even if stalled.
            require(self.state == 'held' and self._delivered,
                    'packed consumer ACK before final result delivery')
        if self.state == 'idle' and request is not None and p['request_ready']:
            self._validate_request(request)
            self.request = replace(request, a=tuple(request.a), b=tuple(request.b))
            p['request_fire'] = True
            if request.clear:
                require(self.group_serial < (1 << 32) - 1, 'packed group sequence exhausted')
                self.group_serial += 1
                self.group = self._group_type(request.opcode, request.steps,
                    self.group_serial, request.slice_mask, profile=2)
                self.index = 0
                self.state = 'begin'
            else:
                self.state = 'issue'
        elif self.state == 'begin':
            if self.service.accept_group(self.owner, self.group):
                self.active = True
                self.tag = PackedTag(self.owner_tag, self.group_serial,
                                     self.service.ticket, self.epoch)
                self._last_write_serial = -1
                self.state = 'issue'
        elif self.state == 'issue':
            r = self.request
            if self.service.accept_step(self.owner, self._step_type(
                    self.index, r.a, r.b, r.clear, r.last, finish=r.last, emit=r.last)):
                index = self.index
                self.index += 1
                if self.service.reset_required:
                    self.poison = self.aborting = True
                elif r.last:
                    self.state = 'wait_result'
                else:
                    require(self.service.result is None and self.service.done is None,
                            'nonfinal packed step exposed a payload or done')
                    self.response = PackedStepAccepted(self.tag, index)
                    self.state = 'reply_step'
        elif self.state == 'reply_step' and result_ready:
            p['result_fire'] = True
            self.request = self.response = None
            self.state = 'idle'
        elif self.state == 'wait_result' and service_result_ready:
            result = self.service.result
            if result is not None:
                require(_uint(result.ticket, 64) and _uint(result.epoch, 64)
                        and type(result.context) is int and type(result.last) is bool
                        and type(result.error) is bool and
                        (result.ticket, result.epoch, result.context, result.last) ==
                        (self.tag.ticket, self.tag.epoch, 0, True),
                        'packed final result metadata mismatch')
                self._held = result
                self.response = PackedResult(self.tag, result, self.request.selected)
                self._exposed, self._delivered = True, False
                self.state = 'reply_final'
        elif self.state == 'reply_final' and result_ready:
            p['result_fire'] = True
            self.request = self.response = None
            self._delivered = True
            self.state = 'held'
        elif self.state == 'held' and request is not None and p['request_ready']:
            require(type(request) is PackedConsumerAck, 'next packed group before consumer ACK')
            require(not self._write_debts, 'packed consumer ACK before write commits')
            p['request_fire'] = True
            self.request = request
            self.state = 'release_result'
        elif self.state == 'release_result' and service_result_ready:
            self._retire_result(p)
            self.state = 'wait_done'
        elif self.state == 'wait_done' and service_done_ready:
            if self._retire_done(p, done_override):
                self.response = PackedRetired(self.tag, self.poison)
                self.state = 'reply_retired'
        elif self.state == 'reply_retired' and result_ready:
            p['result_fire'] = True
            self.request = self.response = self.group = self.tag = None
            self._exposed = self._delivered = False
            self.state = 'locked' if self.poison else 'idle'
        return p


# Descriptive spelling for standalone users; the owner hook uses PackedClient.
PackedMatrixClient = PackedClient
