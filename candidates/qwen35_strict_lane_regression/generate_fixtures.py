#!/usr/bin/env python3
"""Bounded stdlib-only fixture check/generation. Never executes Scala/native code."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
CANDIDATES = HERE.parent
SOURCE = CANDIDATES / 'qwen35_strict_reference/STIMULI.json'
ORACLE = CANDIDATES / 'qwen35_strict_fp32_lane/fraction_reference.py'
OUTPUT = HERE / 'source/StrictFp32LaneFixtures.scala'


def generate():
    spec = importlib.util.spec_from_file_location('fixture_fraction_reference', ORACLE)
    ref = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(ref)
    cases = json.loads(SOURCE.read_text())['cases']
    assert len(cases) == 52
    triples = [tuple(int(c[k], 16) for k in ('a', 'b', 'acc')) for c in cases]
    assert len(set(triples)) == 41
    rows = []
    statuses = {0: 0, 4: 0, 5: 0}
    for i, (case, triple) in enumerate(zip(cases, triples)):
        result = ref.strict(*triple)
        if 'expected' in case:
            assert result == case['expected'], (case['id'], result, case['expected'])
        statuses[result['status']] += 1
        words = ', '.join('h("%08x")' % n for n in (*triple, result['product'], result['value']))
        rows.append('    Vector("%s", %s, %d, %d, %d, %d)' % (
            case['id'], words, result['mul_flags'], result['add_flags'],
            result['attempted'], result['status']))
    assert statuses == {0: 46, 4: 5, 5: 1}
    pins = '\n'.join('// %s sha256=%s' % (p.relative_to(CANDIDATES), hashlib.sha256(p.read_bytes()).hexdigest()) for p in (SOURCE, ORACLE))
    result = '''// SPDX-License-Identifier: Apache-2.0
// Generated by generate_fixtures.py; expected mathematics, NOT hardware results.
// First 20 expectations match the frozen reference stimuli. Remaining signed-zero
// expectations are derived with the repository Fraction oracle, not official DUT output.
%s
package heteronpu.experimental

object StrictFp32LaneFixtures {
  case class Vector(id: String, a: BigInt, b: BigInt, acc: BigInt,
                    product: BigInt, value: BigInt, mulFlags: Int,
                    addFlags: Int, passes: Int, status: Int)
  private def h(s: String): BigInt = BigInt(s, 16)
  val all: Seq[Vector] = Seq(
%s
  )
}
''' % (pins, ',\n'.join(rows))
    return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='regenerate only the isolated Scala fixture')
    args = parser.parse_args()
    expected = generate()
    if args.write:
        OUTPUT.write_text(expected)
    else:
        assert OUTPUT.read_text() == expected, 'fixture drift; review sources before --write'
    print('PASS source/fixture consistency only: 52 requests, 41 unique, 46 OK, 5 MulFatal, 1 AddFatal; no Scala/native/RTL execution')
