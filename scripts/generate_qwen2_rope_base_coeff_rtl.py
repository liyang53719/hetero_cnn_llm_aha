#!/usr/bin/env python3
import math
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "rtl/sfu/qwen2_rope_base_coeff64.sv"
OUT_Q46 = ROOT / "rtl/sfu/qwen2_rope_base_coeff_q46.sv"
THETA = 1_000_000.0

def bits(value):
    return struct.unpack("<I", struct.pack("<f", float(value)))[0]

cos_words = []
sin_words = []
for dim in range(64):
    angle = THETA ** (-2.0 * dim / 128.0)
    cos_words.append(bits(math.cos(angle)))
    sin_words.append(bits(math.sin(angle)))

def case_function(name, words):
    lines = [f" function automatic logic[31:0]{name}(input logic[5:0]index);begin case(index)"]
    lines.extend(f"  6'd{i}:{name}=32'h{word:08x};" for i, word in enumerate(words))
    lines.append(f"  default:{name}=0;endcase end endfunction")
    return "\n".join(lines)

text = """// SPDX-License-Identifier: Apache-2.0
// Generated by scripts/generate_qwen2_rope_base_coeff_rtl.py; do not hand edit.
`timescale 1ns/1ps
module qwen2_rope_base_coeff64(input logic[5:0]index_i,output logic[31:0]cos_o,sin_o);
"""
text += case_function("base_cos", cos_words) + "\n"
text += case_function("base_sin", sin_words) + "\n"
text += " assign cos_o=base_cos(index_i);assign sin_o=base_sin(index_i);\nendmodule\n"
OUT.write_text(text)
qcos = [round(math.cos(THETA ** (-2.0 * dim / 128.0)) * (1 << 46)) & ((1 << 48) - 1) for dim in range(64)]
qsin = [round(math.sin(THETA ** (-2.0 * dim / 128.0)) * (1 << 46)) & ((1 << 48) - 1) for dim in range(64)]
qtext = """// SPDX-License-Identifier: Apache-2.0
// Generated by scripts/generate_qwen2_rope_base_coeff_rtl.py; do not hand edit.
`timescale 1ns/1ps
module qwen2_rope_base_coeff_q46(input logic[5:0]index_i,output logic signed[47:0]cos_o,sin_o);
 always_comb begin case(index_i)
"""
for dim in range(64):
    qtext += f" 6'd{dim}:begin cos_o=48'h{qcos[dim]:012x};sin_o=48'h{qsin[dim]:012x};end\n"
qtext += " default:begin cos_o=0;sin_o=0;end endcase end\nendmodule\n"
OUT_Q46.write_text(qtext)
print("QWEN2_ROPE_BASE_COEFF_RTL_PASS theta=1000000 dims=64 cos0=0x%08x sin0=0x%08x" % (cos_words[0], sin_words[0]))
